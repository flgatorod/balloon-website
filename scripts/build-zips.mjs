// Regenerates site/zip-miles.js: straight-line miles from the home base ZIP
// to every ZIP inside the delivery radius. Run after changing BASE_ZIP or
// MAX_MILES in site/pricing.js:   npm run zips
import { createRequire } from 'node:module';
import { writeFileSync } from 'node:fs';
import { CONFIG } from '../site/pricing.js';

const require = createRequire(import.meta.url);
const zipcodes = require('zipcodes');

const base = zipcodes.lookup(CONFIG.baseZip);
if (!base) throw new Error(`Unknown base ZIP ${CONFIG.baseZip}`);

const maxMiles = Math.max(...CONFIG.deliveryZones.map((z) => z.maxMiles));
const R = 3958.8;
const rad = (d) => (d * Math.PI) / 180;
function miles(a, b) {
  const dLat = rad(b.latitude - a.latitude);
  const dLon = rad(b.longitude - a.longitude);
  const h =
    Math.sin(dLat / 2) ** 2 +
    Math.cos(rad(a.latitude)) * Math.cos(rad(b.latitude)) * Math.sin(dLon / 2) ** 2;
  return 2 * R * Math.asin(Math.sqrt(h));
}

const out = {};
for (const z of Object.values(zipcodes.codes)) {
  if (z.country !== 'US' || typeof z.latitude !== 'number') continue;
  const d = miles(base, z);
  if (d <= maxMiles) out[z.zip] = Math.round(d * 10) / 10;
}

const sorted = Object.fromEntries(Object.entries(out).sort(([a], [b]) => a.localeCompare(b)));
const body =
  `// Generated by scripts/build-zips.mjs — do not edit by hand.\n` +
  `// Straight-line miles from ${CONFIG.baseZip} (${base.city}, ${base.state}), up to ${maxMiles} mi.\n` +
  `export const ZIP_MILES = ${JSON.stringify(sorted)};\n`;
writeFileSync(new URL('../site/zip-miles.js', import.meta.url), body);
console.log(`Wrote ${Object.keys(sorted).length} ZIPs within ${maxMiles} mi of ${CONFIG.baseZip}`);
